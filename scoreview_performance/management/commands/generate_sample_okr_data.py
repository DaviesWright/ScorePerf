"""Generate SYNTHETIC OKR sample data for migration and performance testing.

Nothing here is real. Every row is labelled so it cannot be mistaken for
production data (BUILD.md §1.1 item 12):

* companies are named "SAMPLE ...";
* employees use ``sample.<n>@example.com`` (a reserved domain);
* objectives and key results start with "[Sample]".

The data is deterministic for a given ``--seed``. It includes the awkward cases
real legacy data is likely to hold, so migrations and the OKR changes in
ADR-0012 can be measured against them: non-zero start values, a target of 0,
progress above 100, rows reachable only through the API (start above target,
duplicate key results, key results with no definition), stale stored progress,
archived and inactive records, and definitions with no company.

Synthetic data cannot reproduce genuine legacy inconsistencies. Prefer a
protected production copy when one exists.

Usage::

    python manage.py generate_sample_okr_data --employees 120
    python manage.py generate_sample_okr_data --reset      # remove sample rows only
"""

