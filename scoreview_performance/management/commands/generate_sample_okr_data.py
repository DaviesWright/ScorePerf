class Command(BaseCommand):
    help = "Generate synthetic, labelled OKR sample data (or --reset to remove it)."

    def add_arguments(self, parser):
        parser.add_argument("--seed", type=int, default=20261103)
        parser.add_argument("--employees", type=int, default=120)
        parser.add_argument(
            "--reset",
            action="store_true",
            help="Delete rows previously generated by this command, then exit.",
        )
        parser.add_argument(
            "--force", action="store_true", help="Allow running when DEBUG is off."
        )

    def handle(self, *args, **opts):
        if not settings.DEBUG and not opts["force"]:
            raise CommandError(
                "Refusing to write sample data with DEBUG off. Use --force if intended."
            )
        if opts["reset"]:
            return self._reset()
        if Company.objects.filter(company__startswith=COMPANY_PREFIX).exists():
            raise CommandError("Sample data already exists. Run with --reset first.")
        with transaction.atomic():
            self._generate(random.Random(opts["seed"]), max(opts["employees"], 10))

    # ------------------------------------------------------------------ reset
    def _reset(self):
        companies = Company.objects.filter(company__startswith=COMPANY_PREFIX)
        employees = Employee.objects.filter(
            email__endswith=f"@{EMAIL_DOMAIN}", email__startswith="sample."
        )
        with transaction.atomic():
            Comment.objects.filter(employee_id__in=employees).delete()
            EmployeeKeyResult.objects.filter(
                employee_objective_id__employee_id__in=employees
            ).delete()
            EmployeeObjective.objects.filter(employee_id__in=employees).delete()
            KeyResult.objects.filter(title__startswith=TAG).delete()
            Objective.objects.filter(title__startswith=TAG).delete()
            users = list(employees.values_list("employee_user_id", flat=True))
            employees.delete()
            from horilla_auth.models import HorillaUser

            HorillaUser.objects.filter(pk__in=[u for u in users if u]).delete()
            Department.objects.filter(company_id__in=companies).delete()
            companies.delete()
        self.stdout.write(self.style.SUCCESS("Sample data removed."))

    # --------------------------------------------------------------- generate
    def _generate(self, rng, n_employees):
        main = make_company(f"{COMPANY_PREFIX}Group Holdings (synthetic)")
        second = make_company(f"{COMPANY_PREFIX}Subsidiary Ltd (synthetic)", hq=False)
        depts = []
        for name in DEPARTMENTS:
            d = Department.objects.create(department=f"{TAG} {name}")
            d.company_id.add(main)
            depts.append(d)

        employees = []
        for i in range(n_employees):
            company = second if i % 10 == 9 else main
            employees.append(
                make_employee(
                    company=company,
                    email=f"sample.{i + 1}@{EMAIL_DOMAIN}",
                    first_name=rng.choice(FIRST),
                    last_name=rng.choice(LAST),
                    phone=f"7{i + 1:08d}",
                    department=rng.choice(depts),
                    date_joining=date(2018, 1, 1)
                    + relativedelta(days=rng.randint(0, 2800)),
                )
            )
        # Reporting lines: employee 0 is the head, the next 8 report to them, the rest to those.
        heads = employees[1:9]
        for i, emp in enumerate(employees):
            if i == 0:
                continue
            mgr = employees[0] if i <= 8 else rng.choice(heads)
            EmployeeWorkInformation.objects.filter(employee_id=emp).update(
                reporting_manager_id=mgr
            )
        inactive = rng.sample(employees[9:], k=max(1, n_employees // 30))
        Employee.objects.filter(pk__in=[e.pk for e in inactive]).update(is_active=False)

        key_results = self._key_results(rng, main)
        objectives = self._objectives(rng, main, key_results, employees)
        stats = self._assignments(rng, employees, objectives)
        self._report(main, second, employees, key_results, objectives, stats)

    def _key_results(self, rng, company):
        out = []
        for i in range(60):
            ptype = rng.choices(["%", "#", "$", "€"], weights=[40, 40, 15, 5])[0]
            target = rng.randint(10, 100) if ptype == "%" else rng.randint(10, 500)
            if i % 40 == 7:
                target = 0  # legacy-style: a target of zero
            out.append(
                KeyResult.objects.create(
                    title=f"{TAG} {rng.choice(KR_VERBS)} {rng.choice(KR_NOUNS)} #{i + 1}",
                    description="Synthetic sample key result.",
                    progress_type=ptype,
                    target_value=target,
                    duration=rng.choice([30, 60, 90, 180]),
                    company_id=(
                        None if i % 12 == 5 else company
                    ),  # some definitions have no company
                    archive=(i % 25 == 3),
                )
            )
        return out

    def _objectives(self, rng, company, key_results, employees):
        out = []
        for i, title in enumerate(OBJECTIVES):
            obj = Objective.objects.create(
                title=f"{TAG} {title}",
                description="Synthetic sample objective.",
                duration=(
                    rng.choice([1, 3, 6, 12]) if i % 2 else rng.choice([30, 60, 90])
                ),
                duration_unit="months" if i % 2 else "days",
                company_id=None if i % 11 == 4 else company,
                is_template=(i % 9 == 0),
                archive=(i % 13 == 6),
            )
            obj.key_result_id.set(rng.sample(key_results, k=rng.randint(2, 5)))
            obj.managers.set(rng.sample(employees[:9], k=rng.randint(1, 2)))
            out.append(obj)
        return out

    def _assignments(self, rng, employees, objectives):
        stats = dict(
            emp_objectives=0,
            emp_krs=0,
            nonzero_start=0,
            target_zero=0,
            over_100=0,
            start_above_target=0,
            duplicates=0,
            orphans=0,
            stale=0,
            comments=0,
        )
        for emp in employees:
            for obj in rng.sample(objectives, k=rng.randint(1, 3)):
                start = date(2025, 1, 1) + relativedelta(days=rng.randint(0, 540))
                eo = EmployeeObjective.objects.create(
                    objective_id=obj,
                    employee_id=emp,
                    start_date=start,
                    end_date=start + relativedelta(months=3),
                    status=rng.choices(STATUSES, weights=STATUS_WEIGHTS)[0],
                    archive=(rng.random() < 0.05),
                )
                stats["emp_objectives"] += 1
                krs = list(obj.key_result_id.all())
                for kr in rng.sample(krs, k=min(len(krs), rng.randint(1, 4))):
                    self._employee_kr(rng, eo, kr, start, stats)
                if rng.random() < 0.30:
                    Comment.objects.create(
                        comment="Synthetic sample comment.",
                        employee_id=emp,
                        employee_objective_id=eo,
                    )
                    stats["comments"] += 1
        return stats

    def _employee_kr(self, rng, eo, kr, start, stats):
        target = kr.target_value or 0
        kind = rng.random()
        start_value, current = 0, int(target * rng.uniform(0, 1.3))
        if kind < 0.15 and target:
            start_value = int(target * rng.uniform(0.2, 0.6))
            current = max(start_value, int(target * rng.uniform(0.3, 1.2)))
            stats["nonzero_start"] += 1
        elif kind < 0.18 and target:
            start_value, current = int(target * 1.6), int(
                target * 1.3
            )  # API-only: start above target
            stats["start_above_target"] += 1
        if target == 0:
            stats["target_zero"] += 1
        key_result = kr
        start_date = start
        if rng.random() < 0.02:
            key_result, start_date = None, None  # orphan, as the API can create
            stats["orphans"] += 1
        ekr = EmployeeKeyResult(
            employee_objective_id=eo,
            key_result_id=key_result,
            key_result=(kr.title if key_result is None else None),
            progress_type=kr.progress_type,
            start_value=start_value,
            current_value=current,
            target_value=target,
            start_date=start_date,
            status=rng.choice(STATUSES),
        )
        ekr.save()
        stats["emp_krs"] += 1
        if ekr.progress_percentage > 100:
            stats["over_100"] += 1
        if (
            rng.random() < 0.01
        ):  # duplicate key result on the same objective (not enforced)
            EmployeeKeyResult.objects.create(
                employee_objective_id=eo,
                key_result_id=kr,
                start_value=0,
                current_value=current,
                target_value=target,
                start_date=start,
            )
            stats["duplicates"] += 1
        if rng.random() < 0.02:  # stored progress out of step with its inputs
            EmployeeKeyResult.objects.filter(pk=ekr.pk).update(
                progress_percentage=rng.randint(0, 100)
            )
            stats["stale"] += 1

    def _report(self, main, second, employees, key_results, objectives, stats):
        w = self.stdout.write
        w(self.style.SUCCESS("Sample data generated (synthetic)."))
        w(
            f"  companies: 2 ({main.company!r}, {second.company!r}) | departments: {len(DEPARTMENTS)}"
        )
        w(
            f"  employees: {len(employees)} | key results: {len(key_results)} | objectives: {len(objectives)}"
        )
        for k, v in stats.items():
            w(f"  {k}: {v}")
